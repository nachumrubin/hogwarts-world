"""Transfer the folded scan's pigment onto the original deformable flying surfaces."""
import base64
import io
import json
from pathlib import Path
import struct
import subprocess
import zlib
import numpy as np
from PIL import Image

root=Path(__file__).resolve().parents[1]
species=root/'creature-lab/species'
b=(species/'static/Barn_Owl_50k_Poly_meshy_ai.glb').read_bytes()
length=struct.unpack_from('<I',b,12)[0]
doc=json.loads(b[20:20+length])
def view(i):
    v=doc['bufferViews'][i]
    start=28+length+v.get('byteOffset',0)
    return b[start:start+v['byteLength']]
prim=doc['meshes'][0]['primitives'][0]
def attr(name,dim):
    a=doc['accessors'][prim['attributes'][name]]
    return np.frombuffer(view(a['bufferView']),'<f4').reshape(-1,dim)
p=attr('POSITION',3)
uv=attr('TEXCOORD_0',2)
tex=doc['materials'][0]['pbrMetallicRoughness']['baseColorTexture']['index']
img=np.asarray(Image.open(io.BytesIO(view(doc['images'][doc['textures'][tex]['source']]['bufferView']))).convert('RGB'))
h,w=img.shape[:2]
rgb=img[(uv[:,1]*h).astype(int)%h,(uv[:,0]*w).astype(int)%w]
# Rigid body alignment only. Register pigment in the perched pose so the
# same feather markings follow the original fold and flight morph targets.
model=.18*np.stack([-p[:,2],p[:,1]+.90,p[:,0]-.28],axis=1)
surfaces=json.loads(subprocess.check_output(['node','tools/owl-bind-surfaces.mjs'],cwd=root))
colors=[]
for surface in surfaces:
    samples,remap=np.unique(np.round(surface,3),axis=0,return_inverse=True)
    values=[]
    for start in range(0,len(samples),32):
        query=samples[start:start+32]
        squared=np.maximum(0,(query**2).sum(1)[:,None]+(model**2).sum(1)-2*query@model.T)
        indices=np.argpartition(squared,3,axis=1)[:,:4]
        weight=1/np.maximum(.0005**2,np.take_along_axis(squared,indices,axis=1))
        values.extend(np.einsum('nk,nkc->nc',weight,rgb[indices])/weight.sum(1,keepdims=True))
    colors.append(np.asarray(values)[remap])
payload=base64.b64encode(zlib.compress(np.rint(np.concatenate(colors)).astype('u1').tobytes(),9)).decode()
(species/'owl-binding.js').write_text("// Generated by tools/bind-owl.py. Perched surface pigment (sRGB).\n"
    +f"export const pigment='{payload}';\n",encoding='ascii')
